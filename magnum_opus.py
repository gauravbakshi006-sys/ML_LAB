step = base
while True:
    n = sum(mask[y:y+step, x:x+step].mean() >= 0.5
            for y in range(0, mask.shape[0]-step+1, step)
            for x in range(0, mask.shape[1]-step+1, step))
    if n <= TARGET_TILES or step > base * 20:
        break
    step += max(1, base // 4)
print(f"stride {step}px in mask space -> {n} tiles covering the whole tissue")

cells = [(y, x) for y in range(0, mask.shape[0]-step+1, step)
                for x in range(0, mask.shape[1]-step+1, step)
                if mask[y:y+step, x:x+step].mean() >= 0.5]

