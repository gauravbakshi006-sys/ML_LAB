def align_E_prime(cancer):
    """Intersect the authors' gene list with genes present on the RSEM platform.

    Returns E' restricted to shared genes, plus the aligned expression frame.
    Some of the paper's 5245 genes are absent from TCGA's 20531-gene platform;
    those columns are dropped rather than zero-filled, and the count is reported.
    """
    expr = gene_data[cancer]
    shared = [g for g in paper_gene_list if g in expr.columns]
    missing = len(paper_gene_list) - len(shared)

    col_idx = [paper_gene_list.index(g) for g in shared]
    E_prime = E_prime_full[:, col_idx]
    expr_aligned = expr[shared]

    print(f"{cancer}: E' {E_prime.shape} | {missing} of {len(paper_gene_list)} "
          f"paper genes absent from platform | empty pathway rows "
          f"{int((E_prime.sum(1) == 0).sum())}")
    return E_prime, expr_aligned


