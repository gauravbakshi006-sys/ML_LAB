def load_dino_checkpoint(model, ckpt_path):
    # PyTorch 2.6 defaults weights_only=True, which rejects the training
    # metadata (epoch, args) that main_dino.py saves alongside the weights.
    ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)

    if isinstance(ckpt, dict):
        print("  checkpoint top-level keys:", list(ckpt.keys())[:10])

    for key in ("teacher", "student", "model", "state_dict"):
        if isinstance(ckpt, dict) and key in ckpt:
            ckpt = ckpt[key]
            print(f"  using '{key}' weights")
            break

    ckpt = {k.replace("module.", "").replace("backbone.", ""): v
            for k, v in ckpt.items()}

    missing, unexpected = model.load_state_dict(ckpt, strict=False)
    print(f"  loaded | missing {len(missing)} | unexpected {len(unexpected)}")
    if len(missing) > 20:
        print("  WARNING: many missing keys, may not match ViT-S/8")
        print("  first missing:", missing[:5])
    return model


