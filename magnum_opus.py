        K = min(K_CLUSTERS, len(embeddings))
        labels = KMeans(n_clusters=K, n_init=20, random_state=SEED).fit_predict(embeddings)
        cluster_idx = [np.where(labels == c)[0] for c in range(K)]

        # G=80 independent selections -> G augmented input sequences
        rng = np.random.default_rng(SEED)
        seqs = []
        for g in range(G_AUGMENT):
            sel = []
            for idx in cluster_idx:
                if len(idx):
                    sel.extend(rng.choice(idx, min(PATCHES_PER_CLUST, len(idx)),
                                          replace=False).tolist())
            seqs.append(embeddings[np.array(sel)])

        out_npz = f"{WORK}/features/{cancer}_{patient_id}.npz"
        np.savez_compressed(
            out_npz,
            sequences=np.stack([s for s in seqs if len(s) == len(seqs[0])]),
            coords=np.array([(p[0], p[1]) for p in patches]),
            labels=labels,
        )
        wsi_index.append({"cancer": cancer, "patient_id": patient_id,
                          "n_patches": len(patches), "seq_len": seqs[0].shape[0],
                          "n_aug": len(seqs), "path": out_npz})
        print(f"  saved {len(seqs)} augmented sequences of {seqs[0].shape[0]} patches")

