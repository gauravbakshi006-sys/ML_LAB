import openslide
from skimage.filters import threshold_otsu
from scipy import ndimage as ndi
from PIL import Image


def pick_level_for_magnification(slide, target_mag=TARGET_MAG):
    """Return (level, effective_magnification) closest to target_mag."""
    obj = slide.properties.get(openslide.PROPERTY_NAME_OBJECTIVE_POWER)
    obj = float(obj) if obj else 40.0            # TCGA default when unlabelled
    want_downsample = obj / target_mag           # 40X -> 20X means downsample 2
    level = slide.get_best_level_for_downsample(want_downsample)
    actual = obj / slide.level_downsamples[level]
    return level, actual, obj


def build_tissue_mask(slide, target_downsample=MASK_LEVEL_TARGET):
    """Otsu on HSV saturation, then closing and small-object removal.

    Returns (mask, downsample_factor) where mask is a boolean array and
    downsample_factor maps mask coordinates to level-0 pixels.
    """
    lvl = slide.get_best_level_for_downsample(target_downsample)
    ds  = slide.level_downsamples[lvl]
    thumb = slide.read_region((0, 0), lvl, slide.level_dimensions[lvl]).convert("RGB")

    sat = np.array(thumb.convert("HSV"))[:, :, 1]
    thr = threshold_otsu(sat)
    mask = sat > thr

    # fill holes inside tissue, then drop specks
    mask = ndi.binary_closing(mask, structure=np.ones((5, 5)))
    mask = ndi.binary_fill_holes(mask)
    lab, n = ndi.label(mask)
    if n:
        sizes = ndi.sum(mask, lab, range(1, n + 1))
        keep = np.zeros(n + 1, bool)
        keep[1:][sizes >= 64] = True
        mask = keep[lab]

    return mask, ds, thr


def tissue_patch_coords(mask, mask_ds, level_ds, patch_size=PATCH_SIZE,
                        min_cover=MIN_TISSUE_COVER):
    """Grid the mask and return level-0 coordinates of tissue-covered patches."""
    # how many mask pixels one patch spans
    patch_in_mask = max(1, int(round(patch_size * level_ds / mask_ds)))
    step_level0   = int(round(patch_size * level_ds))

    coords = []
    for my in range(0, mask.shape[0] - patch_in_mask + 1, patch_in_mask):
        for mx in range(0, mask.shape[1] - patch_in_mask + 1, patch_in_mask):
            tile = mask[my:my + patch_in_mask, mx:mx + patch_in_mask]
            if tile.mean() >= min_cover:
                coords.append((int(mx * mask_ds), int(my * mask_ds)))
    return coords, step_level0


def extract_patches(svs_path, target=PATCH_TARGET, seed=SEED, show=False):
    slide = openslide.OpenSlide(svs_path)
    level, actual_mag, obj = pick_level_for_magnification(slide)
    level_ds = slide.level_downsamples[level]

    # Not every pyramid contains an exact 20X level. openslide returns the
    # largest level whose downsample does not exceed what we asked for, so a
    # 40X slide with levels [1, 4, 16] yields level 0 at 40X. In that case read
    # a proportionally larger region and resize down, which reproduces the
    # paper's 20X field of view rather than silently using 40X.
    scale = actual_mag / TARGET_MAG            # 1.0 when the level is already 20X
    read_size = int(round(PATCH_SIZE * scale))

    mask, mask_ds, thr = build_tissue_mask(slide)
    coords, _ = tissue_patch_coords(mask, mask_ds, level_ds)

    print(f"  scanned at {obj:.0f}X native -> level {level} = {actual_mag:.1f}X"
          f"{'' if abs(scale - 1) < 0.01 else f', reading {read_size}px and resizing to {PATCH_SIZE}px'}"
          f" | mask {mask.shape} (otsu {thr}) | {len(coords)} tissue positions")

    rng = np.random.default_rng(seed)
    rng.shuffle(coords)
    coords = coords[:target]

    patches = []
    for (x, y) in coords:
        region = slide.read_region((x, y), level, (read_size, read_size)).convert("RGB")
        if read_size != PATCH_SIZE:
            region = region.resize((PATCH_SIZE, PATCH_SIZE), Image.BILINEAR)
        patches.append((x, y, region))

    if show:
        thumb = slide.get_thumbnail((900, 900))
        fig, ax = plt.subplots(1, 2, figsize=(15, 6))
        ax[0].imshow(thumb); ax[0].set_title(
            f"WSI  {slide.dimensions[0]} x {slide.dimensions[1]}"); ax[0].axis("off")
        ax[1].imshow(mask, cmap="gray"); ax[1].set_title(
            f"tissue mask  (Otsu on saturation, thr={thr})"); ax[1].axis("off")
        plt.tight_layout(); plt.show()

    slide.close()
    return patches


